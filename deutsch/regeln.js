<h3>Nach Bedeutung</h3>
<ul>
<li><b>Wochentage, Monate, Jahreszeiten</b>: der Montag, der Januar, der Sommer, der Winter.</li>
<li><b>Himmelsrichtungen</b>: der Norden, der Süden.</li>
