<p>Die meisten Verben nehmen den <b>Akkusativ</b>. Eine wichtige Gruppe nimmt aber den <b>Dativ</b>. Die musst du lernen, denn auf Schwedisch (<i>hjälpa mig, fråga mig</i>) und Englisch (help me, ask me) siehst du keinen Unterschied.</p>
